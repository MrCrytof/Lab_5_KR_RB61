#ifndef LAB5_H
#define LAB5_H

#include <stdio.h>
#include <stdlib.h>
#include <math.h>

/**
 * @brief Структура для збереження вхідних параметрів та даних студента.
 * 
 * @details Містить граничні значення аргументу, крок обчислень, кількість точок,
 *          шифр навчальної групи та ПІБ студента, зчитані з вхідного файлу.
 */
typedef struct {
    double x_start;
    double x_end;
    int num_points;
    double step;
    char group[50];
    char name[100];
} LabData;

/**
 * @brief Зчитує вхідні дані та параметри з текстового файлу.
 *
 * @details Відкриває вказаний текстовий файл у режимі читання, зчитує
 *          початкове та кінцеве значення аргументу, кількість точок,
 *          крок обчислень, шифр навчальної групи та ПІБ студента.
 *          Перевіряє коректність зчитаних даних і зберігає їх
 *          у структуру LabData.
 *
 * @param[in] filename Шлях до вхідного текстового файлу.
 * @param[out] data Вказівник на структуру LabData для збереження зчитаних даних.
 * @return int Повертає 1 у разі успішного зчитування, або 0 при виникненні помилки.
 */
int readInputData(const char *filename, LabData *data);

/**
 * @brief Обчислює значення функції, формує таблицю та зберігає дані у текстовий і бінарний файли.
 *
 * @details Проходить по точках у заданому діапазоні, обчислює значення
 *          математичної функції відповідно до варіанта, записує таблицю
 *          та інформацію про студента в текстовий файл, а кількість точок
 *          і пари значень (x, f(x)) — у бінарний файл.
 *
 * @param[in] data Вказівник на структуру з вхідними параметрами та метаданими.
 * @param[in] txtFilename Шлях до вихідного текстового файлу.
 * @param[in] binFilename Шлях до вихідного бінарного файлу.
 * @return int Повертає 1 у разі успішного виконання, або 0 при помилці відкриття, обчислення, запису чи закриття файлів.
 */
int generateAndSaveFiles(const LabData *data, const char *txtFilename, const char *binFilename);

/**
 * @brief Зчитує дані з бінарного файлу в динамічний масив та виводить їх на екран у вигляді таблиці.
 * 
 * @details Відкриває бінарний файл, зчитує загальну кількість точок N, виділяє динамічну
 *          пам'ять під масив розміром 2N для збереження пар (x, f(x)), заповнює його,
 *          виводить таблицю в консоль та безпечно звільняє виділену пам'ять.
 *
 * @param[in] binFilename Шлях до бінарного файлу для зчитування.
 * @return int Повертає 1 у разі успішного виконання, або 0 при помилці відкриття чи читання файлу або виділення пам'яті.
 */
int readAndPrintBinaryFile(const char *binFilename);

#endif